defmodule Modbuv.CRCTest do
  use ExUnit.Case, async: true
  alias Modbuv.CRC

  test "known Modbus vectors" do
    assert CRC.crc(<<0x01, 0x05, 0x0B, 0xB8, 0x00, 0x00>>) == 0xCB4F
    assert CRC.crc(<<0x01, 0x05, 0x0B, 0xB8, 0xFF, 0x00>>) == 0x3B0E
    assert CRC.crc(<<0x01, 0x01, 0x0B, 0xB8, 0x00, 0x01>>) == 0xCB7F
    assert CRC.crc(<<0x01, 0x01, 0x01, 0x00>>) == 0x8851
    assert CRC.crc(<<0x01, 0x03, 0x00, 0x00, 0x00, 0x01>>) == 0x0A84
  end

  test "empty input returns the initial value" do
    assert CRC.crc(<<>>) == 0xFFFF
  end
end
